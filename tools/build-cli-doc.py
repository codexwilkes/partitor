"""Build docs/cli.json and docs/COMMANDS.md from the real code.

Sources: `build_parser()` and `item_menu` in lib/partitor/cli_main.py. Do not edit the
two files; run this tool. `--check` exits 1 when a committed file is old.
cli.json is the machine source for tools that read partitor (the website).
"""
from __future__ import annotations

import argparse
import ast
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "lib"))
from partitor import cli_main  # noqa: E402

JSON_OUT = ROOT / "docs" / "cli.json"
MD_OUT = ROOT / "docs" / "COMMANDS.md"


def menu_keys() -> list[str]:
    """The keys of item_menu: the strings that `k` is compared with."""
    tree = ast.parse((ROOT / "lib" / "partitor" / "cli_main.py").read_text(encoding="utf-8"))
    fn = next(n for n in ast.walk(tree) if isinstance(n, ast.FunctionDef) and n.name == "item_menu")
    keys = set()
    for n in ast.walk(fn):
        if (isinstance(n, ast.Compare) and isinstance(n.left, ast.Name) and n.left.id == "k"
                and isinstance(n.ops[0], (ast.Eq, ast.In))):
            c = n.comparators[0]
            for e in (c.elts if isinstance(c, ast.Tuple) else [c]):
                if isinstance(e, ast.Constant) and isinstance(e.value, str):
                    keys.add(e.value)
    return sorted(keys)


def arg_info(a: argparse.Action) -> dict:
    d = {"flags": list(a.option_strings) or [a.dest], "help": (a.help or "").replace("%(default)s", "")}
    if not a.option_strings:
        d["positional"] = True
    if a.choices:
        d["choices"] = [str(c) for c in a.choices]
    if a.metavar:
        d["metavar"] = a.metavar if isinstance(a.metavar, str) else " ".join(a.metavar)
    return d


def data() -> dict:
    p = cli_main.build_parser()
    sp = next(a for a in p._actions if isinstance(a, argparse._SubParsersAction))
    helps = {c.dest: c.help for c in sp._choices_actions}
    cmds = []
    for name, sub in sp.choices.items():
        if name == "plan":                  # its own parser: the stub in build_parser has no arguments
            sub = cli_main.plan_parser()
        args = [arg_info(a) for a in sub._actions if not isinstance(a, argparse._HelpAction)]
        cmds.append({"name": name, "help": helps.get(name) or "", "args": args})
    return {"version": cli_main.VERSION, "commands": cmds, "menu_keys": menu_keys()}


def _sentence(t: str) -> str:
    t = (t or "").strip().rstrip(".")
    return (t[:1].upper() + t[1:] + ".") if t else ""


def markdown(d: dict) -> str:
    out = ["<!-- SPDX-License-Identifier: AGPL-3.0-or-later -->",
           "<!-- Copyright (C) 2026 Nathan Wilkes and partitor contributors -->",
           "<!-- Generated by tools/build-cli-doc.py from the code. Do not edit. -->",
           f"# Commands (partitor {d['version']})", "",
           "Every command and option of `partitor`. The operator guide "
           "(`docs/operator/guide.md`) shows the usual order of work; this page lists everything. "
           "The same data is in `docs/cli.json`.", "",
           "Run `partitor` with no command for the menu. Most commands take an item id: "
           "`12` or `2026-10-0012`.", ""]
    for c in d["commands"]:
        out += [f"## `partitor {c['name']}`", "", _sentence(c["help"]), ""]
        if c["args"]:
            out += ["| Argument | Meaning |", "|---|---|"]
            for a in c["args"]:
                f = ", ".join(f"`{x}`" for x in a["flags"])
                if a.get("metavar") and not a.get("positional"):
                    f += f" `{a['metavar']}`"
                h = a["help"].replace("|", "\\|").replace("\n", " ")
                if a.get("choices"):
                    h += (" " if h else "") + "Values: " + ", ".join(f"`{x}`" for x in a["choices"]) + "."
                out.append(f"| {f} | {h} |")
            out.append("")
    out += ["## Menu keys of one item", "",
            "The keys of the item menu: " + ", ".join(f"`{k}`" for k in d["menu_keys"]) + ". "
            "The guide explains each key.", ""]
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    d = data()
    new = {JSON_OUT: json.dumps(d, indent=1, ensure_ascii=False) + "\n", MD_OUT: markdown(d) + "\n"}
    bad = 0
    for path, text in new.items():
        if a.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != text:
                print(f"build-cli-doc: {path.relative_to(ROOT)} is old (run tools/build-cli-doc.py)")
                bad = 1
        else:
            path.write_text(text, encoding="utf-8")
    return bad


if __name__ == "__main__":
    sys.exit(main())
